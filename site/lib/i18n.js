let current = "zh";

export function setUiLang(lang) { current = UI_LANGS.includes(lang) ? lang : "zh"; return current; }
export function uiLang() { return current; }

export function t(key, vars = {}, lang = current) {
  const s = DICT[lang]?.[key] ?? DICT.zh[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// Pick a {zh, vi} text object (or a field pair like nameZh / nameVi) for the current UI language.
export function pick(obj, lang = current) {
  if (obj == null) return "";
  if (typeof obj === "string") return obj;
  return obj[lang] ?? obj.zh ?? "";
}
